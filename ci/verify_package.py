#!/usr/bin/env python3
"""Offline, no-API preflight for GitHub Actions build package."""
from pathlib import Path
import sys
def main():
    files=[
        "README.md",
        "ci/BUILD_PROMPT.md",
        "ci/validate_plist.py",
        "spec/言归_Shortcuts_构建规格.md",
        ".github/workflows/build-shortcut.yml",
    ]
    for filename in files:
        p=Path(filename)
        if not p.is_file() or p.stat().st_size < 50:
            sys.exit(f"Missing/empty required file: {filename}")
    spec=Path(files[3]).read_text()
    for name in ("note.create","note.search","calendar.create","calendar.search","reminder.create","reminder.search"):
        if name not in spec:
            sys.exit(f"Missing action in spec: {name}")
    yml=Path(files[4]).read_text()
    for name in ("workflow_dispatch","actions/checkout","upload-artifact"):
        if name not in yml:
            sys.exit(f"Missing CI component: {name}")
    print("Source package preflight passed. No Shortcut generated by this test.")
if __name__=="__main__":
    main()
